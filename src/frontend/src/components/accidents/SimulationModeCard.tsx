import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Label } from "@/components/ui/label";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { Switch } from "@/components/ui/switch";
import {
  useCameras,
  useGenerateAccidentEvent,
  useSettings,
  useUpdateSettings,
} from "@/hooks/useRoadwatch";
import { cameraLabel } from "@/lib/roadwatch";
import { cn } from "@/lib/utils";
import { FlaskConical, Loader2, Radio, ShieldAlert } from "lucide-react";
import { useState } from "react";

export function SimulationModeCard() {
  const { data: settings } = useSettings();
  const { data: cameras } = useCameras();
  const updateSettings = useUpdateSettings();
  const generateEvent = useGenerateAccidentEvent();
  const [cameraId, setCameraId] = useState<string>("");
  const [generated, setGenerated] = useState(false);

  const simulation = settings?.simulationMode ?? true;
  const cameraList = cameras ?? [];
  const selectedCamera = cameraList.find((c) => c.id.toString() === cameraId);

  function handleToggle(next: boolean) {
    if (!settings) return;
    updateSettings.mutate({ ...settings, simulationMode: next });
  }

  function handleGenerate() {
    if (!selectedCamera) return;
    setGenerated(false);
    generateEvent.mutate(
      {
        cameraId: selectedCamera.id,
        confidence: null,
        summary: `Simulated potential accident generated for ${cameraLabel(selectedCamera)}.`,
        snapshotRef: null,
      },
      {
        onSuccess: () => {
          setGenerated(true);
          window.setTimeout(() => setGenerated(false), 4000);
        },
      },
    );
  }

  return (
    <Card data-ocid="accidents.simulation_card" className="gap-4">
      <CardHeader>
        <CardTitle className="flex items-center gap-2 font-display text-base">
          <FlaskConical className="size-4 text-warning" aria-hidden="true" />
          Simulation mode
        </CardTitle>
        <p className="text-sm text-muted-foreground">
          When enabled, the analysis pipeline runs in clearly labelled
          simulation mode and every generated event is marked as simulated.
        </p>
      </CardHeader>
      <CardContent className="flex flex-col gap-5">
        <div className="flex items-center justify-between gap-4 rounded-lg border border-border bg-secondary/40 p-4">
          <div className="flex items-center gap-3">
            <span
              className={cn(
                "flex size-9 items-center justify-center rounded-md",
                simulation
                  ? "bg-warning/15 text-warning"
                  : "bg-success/15 text-success",
              )}
            >
              <Radio className="size-4" aria-hidden="true" />
            </span>
            <div>
              <Label htmlFor="accidents.simulation_switch" className="text-sm">
                Simulation mode
              </Label>
              <p className="text-xs text-muted-foreground">
                {simulation
                  ? "Events are generated by the simulation pipeline."
                  : "Pipeline reports live model output."}
              </p>
            </div>
          </div>
          <Switch
            id="accidents.simulation_switch"
            data-ocid="accidents.simulation_switch"
            checked={simulation}
            disabled={!settings || updateSettings.isPending}
            onCheckedChange={handleToggle}
            aria-label="Toggle simulation mode"
          />
        </div>

        <div className="flex flex-col gap-3 border-t border-border pt-5">
          <Label htmlFor="accidents.generate_camera" className="text-sm">
            Generate a potential accident event
          </Label>
          <div className="flex flex-col gap-3 sm:flex-row sm:items-center">
            <Select value={cameraId} onValueChange={setCameraId}>
              <SelectTrigger
                id="accidents.generate_camera"
                data-ocid="accidents.generate_camera_select"
                className="w-full sm:w-72"
              >
                <SelectValue placeholder="Select a camera" />
              </SelectTrigger>
              <SelectContent>
                {cameraList.map((camera) => (
                  <SelectItem
                    key={camera.id.toString()}
                    value={camera.id.toString()}
                  >
                    {cameraLabel(camera)}
                  </SelectItem>
                ))}
              </SelectContent>
            </Select>
            <Button
              type="button"
              variant="destructive"
              data-ocid="accidents.generate_event_button"
              onClick={handleGenerate}
              disabled={!selectedCamera || generateEvent.isPending}
            >
              {generateEvent.isPending ? (
                <Loader2 className="size-4 animate-spin" aria-hidden="true" />
              ) : (
                <ShieldAlert className="size-4" aria-hidden="true" />
              )}
              Generate event
            </Button>
          </div>
          <p className="text-xs text-muted-foreground">
            Creates the incident record and its emergency alert for the selected
            camera.
          </p>
          {generated && (
            <span
              data-ocid="accidents.generate_success_state"
              className="text-sm text-success"
            >
              Potential accident event created.
            </span>
          )}
          {generateEvent.isError && (
            <span
              data-ocid="accidents.generate_error_state"
              role="alert"
              className="text-sm text-destructive"
            >
              Could not generate the event. Please retry.
            </span>
          )}
        </div>
      </CardContent>
    </Card>
  );
}
